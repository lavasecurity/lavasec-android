"""Effective generated values must survive; no credential plaintext may survive."""

import base64
import contextlib
import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import android_public_config_evidence as evidence


PUBLIC_KEY = "sb_publishable_fixture_public_only"
FIELDS = {
    "DEBUG": ("boolean", 'Boolean.parseBoolean("true")'),
    "APPLICATION_ID": ("String", '"com.lavasec.app.debug"'),
    "BUILD_TYPE": ("String", '"debug"'),
    "VERSION_CODE": ("int", "1"),
    "VERSION_NAME": ("String", '"0.1.0-debug"'),
    "PLAY_CLOUD_PROJECT_NUMBER": ("long", "63568815967L"),
    "GOOGLE_SERVER_CLIENT_ID": ("String", '"874608002455-fixture.apps.googleusercontent.com"'),
    "APPLE_BROWSER_OAUTH_ENABLED": ("boolean", "false"),
    "BACKEND_URL": ("String", '"https://api.lavasecurity.app/"'),
    "SUPABASE_URL": ("String", '"https://fixture.supabase.co/"'),
    "BACKUP_PASSKEY_RP_ORIGIN": ("String", '""'),
    "SUPABASE_PUBLISHABLE_KEY": ("String", json.dumps(PUBLIC_KEY)),
}


def java_source(fields):
    return ("/** Generated by AGP. */\npackage com.lavasec.app;\n\npublic final class BuildConfig {\n"
            + "".join(f"  public static final {kind} {name} = {value};\n" for name, (kind, value) in fields.items())
            + "}\n").encode()


def jwt(role):
    encode = lambda item: base64.urlsafe_b64encode(json.dumps(item).encode()).decode().rstrip("=")
    return ".".join((encode({"alg": "HS256", "typ": "JWT"}), encode({"role": role}), "fixtureSignature"))


class AndroidPublicConfigEvidenceTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        source = self.root / evidence.SOURCE_CONFIG
        source.parent.mkdir(parents=True)
        source.write_text("# public defaults\nLAVA_BACKEND_URL=https://default.invalid/\n")
        self.artifacts = self.root / "artifacts"
        self.artifacts.mkdir()
        self.output = self.artifacts / "public-config.json"
        for args in (("init", "--quiet"), ("add", str(evidence.SOURCE_CONFIG)),
                     ("-c", "user.name=Public Fixture", "-c", "user.email=fixture@example.invalid", "commit", "--quiet", "-m", "fixture")):
            subprocess.run(["git", "-C", str(self.root), *args], check=True, capture_output=True)
        self.head = subprocess.check_output(["git", "-C", str(self.root), "rev-parse", "HEAD"], text=True).strip()
        self.write_variant("debug")

    def write_variant(self, variant, changes=None, omit=()):
        fields = dict(FIELDS)
        if variant == "release":
            fields.update({"DEBUG": ("boolean", "false"), "APPLICATION_ID": ("String", '"com.lavasec.app"'),
                           "BUILD_TYPE": ("String", '"release"'), "VERSION_NAME": ("String", '"0.1.0"'),
                           "BACKUP_PASSKEY_RP_ORIGIN": ("String", '"https://lavasecurity.app"')})
        fields.update(changes or {})
        for name in omit:
            del fields[name]
        path = self.root / evidence.GENERATED_BASE / variant / evidence.NAMESPACE_PATH
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(java_source(fields))
        return path

    def run_cli(self, variants=("debug",), output=None):
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = evidence.main(["--root", str(self.root), "--variants", *variants,
                                  "--output", str(output or self.output)])
        return code, stdout.getvalue(), stderr.getvalue()

    def test_foss_coordinates_are_empty_and_service_leak_fails_closed(self):
        fields = dict(FIELDS)
        fields.update({"APPLICATION_ID": ("String", '"com.lavasec.app.foss"'), "BUILD_TYPE": ("String", '"release"'),
                       "DEBUG": ("boolean", "false"), "IS_FOSS": ("boolean", "true"), "FLAVOR": ("String", '"foss"'),
                       "PLAY_CLOUD_PROJECT_NUMBER": ("long", "0L")})
        for name in ("GOOGLE_SERVER_CLIENT_ID", "BACKEND_URL", "SUPABASE_URL", "SUPABASE_PUBLISHABLE_KEY", "BACKUP_PASSKEY_RP_ORIGIN"):
            fields[name] = ("String", '""')
        path = self.root / evidence.GENERATED_BASE / "foss" / "release" / evidence.NAMESPACE_PATH
        path.parent.mkdir(parents=True)
        path.write_bytes(java_source(fields))
        result = evidence.collect(self.root, ["fossRelease"])
        self.assertTrue(result["variants"]["fossRelease"]["effective"]["IS_FOSS"])
        for name, value in (("BACKEND_URL", '"https://api.lavasecurity.app"'), ("SUPABASE_PUBLISHABLE_KEY", '"sb_publishable_leaked"')):
            changed = dict(fields, **{name: ("String", value)})
            path.write_bytes(java_source(changed))
            with self.assertRaisesRegex(evidence.EvidenceError, "FOSS contains excluded"):
                evidence.collect(self.root, ["fossRelease"])

    def test_debug_receipt_uses_generated_override_and_hashes_exact_inputs(self):
        path = self.write_variant("debug", {"BACKEND_URL": ("String", '"https://actual-override.example/"'),
                                            "VERSION_CODE": ("int", "27"),
                                            "UNRELATED_SECRET": ("String", '"NEVER_RETAIN_THIS_UNKNOWN_FIELD"')})
        code, stdout, stderr = self.run_cli()
        self.assertEqual((code, stderr), (0, ""))
        receipt = json.loads(self.output.read_text())
        effective = receipt["variants"]["debug"]["effective"]
        self.assertEqual(receipt["source_sha"], self.head)
        self.assertEqual(effective["BACKEND_URL"], "https://actual-override.example/")
        self.assertEqual(effective["VERSION_CODE"], 27)
        self.assertEqual(effective["BACKUP_PASSKEY_RP_ORIGIN"], "")
        self.assertEqual(set(effective), set(evidence.FIELD_TYPES))
        self.assertEqual(receipt["source_service_config"]["sha256"], hashlib.sha256((self.root / evidence.SOURCE_CONFIG).read_bytes()).hexdigest())
        self.assertEqual(receipt["variants"]["debug"]["build_config"]["sha256"], hashlib.sha256(path.read_bytes()).hexdigest())
        self.assertEqual(effective["SUPABASE_PUBLISHABLE_KEY"], {"sha256": hashlib.sha256(PUBLIC_KEY.encode()).hexdigest(),
                         "validated_public": True, "format": "publishable"})
        retained = self.output.read_text() + stdout + stderr
        self.assertNotIn(PUBLIC_KEY, retained)
        self.assertNotIn("NEVER_RETAIN_THIS_UNKNOWN_FIELD", retained)
        self.assertNotIn("default.invalid", retained)

    def test_both_variants_bind_separate_generated_metadata(self):
        self.write_variant("release", {"VERSION_CODE": ("int", "1000004"), "VERSION_NAME": ("String", '"0.1.0-rc4"')})
        code, _, stderr = self.run_cli(("debug", "release"))
        self.assertEqual((code, stderr), (0, ""))
        receipt = json.loads(self.output.read_text())
        self.assertEqual(set(receipt["variants"]), {"debug", "release"})
        release = receipt["variants"]["release"]["effective"]
        self.assertEqual(release["APPLICATION_ID"], "com.lavasec.app")
        self.assertFalse(release["DEBUG"])
        self.assertEqual(release["VERSION_CODE"], 1000004)
        self.assertEqual(release["BACKUP_PASSKEY_RP_ORIGIN"], "https://lavasecurity.app")
        self.assertLess(self.output.stat().st_size, evidence.MAX_EVIDENCE_BYTES)

    def test_legacy_anon_jwt_is_hashed_without_retaining_claims_or_key(self):
        key = jwt("anon")
        self.write_variant("debug", {"SUPABASE_PUBLISHABLE_KEY": ("String", json.dumps(key))})
        code, stdout, stderr = self.run_cli()
        self.assertEqual(code, 0)
        text = self.output.read_text()
        value = json.loads(text)["variants"]["debug"]["effective"]["SUPABASE_PUBLISHABLE_KEY"]
        self.assertEqual(value["format"], "legacy_anon_jwt")
        self.assertEqual(value["sha256"], hashlib.sha256(key.encode()).hexdigest())
        self.assertNotIn(key, text + stdout + stderr)

    def test_invalid_keys_fail_closed_without_diagnostic_disclosure(self):
        for key in ("sb_secret_fixture_DO_NOT_PRINT", jwt("service_role"), jwt("authenticated"),
                    "sb_publishable_", "", "bad.public.key", "sb_publishable_fixture\nDO_NOT_PRINT"):
            with self.subTest(key_kind=key.split("_", 1)[0]):
                self.write_variant("debug", {"SUPABASE_PUBLISHABLE_KEY": ("String", json.dumps(key))})
                code, stdout, stderr = self.run_cli()
                self.assertEqual(code, 1)
                self.assertFalse(self.output.exists())
                if key:
                    self.assertNotIn(key, stdout + stderr)
                self.assertNotIn("DO_NOT_PRINT", stdout + stderr)

    def test_missing_build_source_config_or_git_head_refuses_receipt(self):
        path = self.root / evidence.GENERATED_BASE / "debug" / evidence.NAMESPACE_PATH
        path.unlink()
        self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())
        self.write_variant("debug")
        source = self.root / evidence.SOURCE_CONFIG
        original = source.read_bytes()
        source.unlink()
        self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())
        source.write_bytes(original)
        (self.root / ".git" / "HEAD").write_text("ref: refs/heads/nonexistent\n")
        self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())

    def test_every_required_field_missing_wrong_type_or_malformed_is_refused(self):
        for name, expected in evidence.FIELD_TYPES.items():
            with self.subTest(field=name, fault="missing"):
                self.write_variant("debug", omit=(name,))
                self.assertEqual(self.run_cli()[0], 1)
            with self.subTest(field=name, fault="type"):
                self.write_variant("debug", {name: ("String" if expected != "String" else "boolean", '"wrong"' if expected != "String" else "false")})
                self.assertEqual(self.run_cli()[0], 1)
            with self.subTest(field=name, fault="expression"):
                self.write_variant("debug", {name: (expected, 'System.getenv("DO_NOT_PRINT")')})
                code, stdout, stderr = self.run_cli()
                self.assertEqual(code, 1)
                self.assertNotIn("DO_NOT_PRINT", stdout + stderr)
        self.assertFalse(self.output.exists())

    def test_comments_cannot_supply_missing_fields_and_duplicates_refuse(self):
        path = self.write_variant("debug", omit=("BACKEND_URL",))
        data = path.read_text().replace("public final class", '// public static final String BACKEND_URL = "https://fake.example/";\npublic final class')
        path.write_text(data)
        self.assertEqual(self.run_cli()[0], 1)
        path = self.write_variant("debug")
        path.write_text(path.read_text().replace("}\n", '  public static final String BACKEND_URL = "https://fake.example/";\n}\n'))
        self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())

    def test_variant_identity_and_debug_passkey_activation_refuse(self):
        for changes in ({"APPLICATION_ID": ("String", '"com.lavasec.app"')},
                        {"BUILD_TYPE": ("String", '"release"')}, {"DEBUG": ("boolean", "false")},
                        {"BACKUP_PASSKEY_RP_ORIGIN": ("String", '"https://lavasecurity.app"')}):
            with self.subTest(fields=list(changes)):
                self.write_variant("debug", changes)
                self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())

    def test_invalid_origins_google_coordinates_and_version_refuse(self):
        for field, value in (("BACKEND_URL", '"https://user:DO_NOT_PRINT@example.com/"'),
                             ("SUPABASE_URL", '"http://example.com/"'), ("BACKEND_URL", '"https://example.com/?token=DO_NOT_PRINT"'),
                             ("GOOGLE_SERVER_CLIENT_ID", '"not-an-oauth-client"'), ("PLAY_CLOUD_PROJECT_NUMBER", "0L"),
                             ("VERSION_CODE", "0"), ("VERSION_CODE", "010"), ("VERSION_NAME", '""')):
            with self.subTest(field=field):
                self.write_variant("debug", {field: (evidence.FIELD_TYPES[field], value)})
                code, stdout, stderr = self.run_cli()
                self.assertEqual(code, 1)
                self.assertNotIn("DO_NOT_PRINT", stdout + stderr)
        self.assertFalse(self.output.exists())

    def test_optional_sdk_metadata_only_comes_from_actual_generated_fields(self):
        self.write_variant("debug", {"MIN_SDK": ("int", "28"), "TARGET_SDK": ("int", "36")})
        receipt = evidence.collect(self.root, ["debug"])
        self.assertEqual(receipt["variants"]["debug"]["effective"]["MIN_SDK"], 28)
        self.assertEqual(receipt["variants"]["debug"]["effective"]["TARGET_SDK"], 36)
        self.write_variant("debug")
        self.assertNotIn("MIN_SDK", evidence.collect(self.root, ["debug"])["variants"]["debug"]["effective"])

    def test_invalid_variant_selection_missing_release_and_output_refuse(self):
        self.assertEqual(self.run_cli(("debug", "debug"))[0], 1)
        self.assertEqual(self.run_cli(("debug", "release"))[0], 1)
        self.assertEqual(self.run_cli(output=self.root / "absent" / "config.json")[0], 1)
        self.assertEqual(self.run_cli(output=self.artifacts / "config.txt")[0], 1)
        target = self.artifacts / "target.json"
        target.write_text("UNCHANGED")
        self.output.symlink_to(target)
        self.assertEqual(self.run_cli()[0], 1)
        self.assertEqual(target.read_text(), "UNCHANGED")

    def test_oversized_generated_input_refuses_before_output(self):
        path = self.write_variant("debug")
        path.write_bytes(b" " * (evidence.MAX_INPUT_BYTES + 1))
        self.assertEqual(self.run_cli()[0], 1)
        self.assertFalse(self.output.exists())


if __name__ == "__main__":
    unittest.main()
