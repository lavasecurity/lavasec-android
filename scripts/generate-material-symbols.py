#!/usr/bin/env python3
"""Rebuild Android's licensed 350-weight subset. Requires fonttools==4.60.1.
Subsets BEFORE instancing to bound memory. No dependency on system fonts.
"""
import hashlib
import io
import json
from pathlib import Path
from urllib.parse import quote
from urllib.request import urlopen
from fontTools import subset, __version__ as font_tools_version
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[1]
if font_tools_version != '4.60.1':
    raise RuntimeError('Use fonttools==4.60.1 to reproduce the committed subset')
CONFIG = ROOT / 'android/design-system/icons/material-symbols.json'
config = json.loads(CONFIG.read_text())
custom_path = CONFIG.with_name('lava-connection-glyphs.json')
custom_bytes = custom_path.read_bytes()
custom = json.loads(custom_bytes)['glyphs']
base = f'https://raw.githubusercontent.com/google/material-design-icons/{config["sourceRevision"]}/'
font_path = 'variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf'
def fetch(path):
    with urlopen(base + quote(path, safe='/'), timeout=60) as response:
        return response.read()
source = fetch(font_path)
assert hashlib.sha256(source).hexdigest() == config["sourceSha256"], "Pinned font content changed"
points = dict(line.split() for line in fetch(font_path.replace('.ttf', '.codepoints')).decode().splitlines())
names = sorted(set(config['symbols'].values()))
codepoints = {name:int(custom[name]['codepoint'] if name in custom else points[name], 16) for name in names}
assert len(set(codepoints.values())) == len(codepoints), 'Glyph codepoints must be distinct'
assert not set(int(g['codepoint'], 16) for g in custom.values()) & set(int(p, 16) for p in points.values()), 'Custom codepoints must not replace Material glyphs'
font = TTFont(io.BytesIO(source), recalcTimestamp=False)
options = subset.Options()
options.recalc_timestamp = False
options.layout_features = []
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=[codepoints[name] for name in names if name not in custom])
subsetter.subset(font)
assets = ROOT / 'android/app/src/main/assets/fonts'
assets.mkdir(parents=True, exist_ok=True)
receipt = {'sourceRevision':config['sourceRevision'], 'sourceSha256':hashlib.sha256(source).hexdigest(), 'fontTools':'4.60.1', 'weight':350, 'grade':0, 'opticalSize':24, 'files':{}}
receipt['customGlyphsSha256'] = hashlib.sha256(custom_bytes).hexdigest()
for fill, suffix in [(0,''), (1,'Filled')]:
    family = 'MaterialSymbolsRounded350' + suffix
    instance = instantiateVariableFont(font, {'wght':350, 'GRAD':0, 'opsz':24, 'FILL':fill}, inplace=False)
    # Independently authored 24-unit vectors share the font's advance and baseline.
    # Both Compose and inline RN text therefore render exactly the same outlines.
    units = instance['head'].unitsPerEm
    for name in names:
        if name not in custom:
            continue
        definition = custom[name]
        pen = TTGlyphPen(None)
        transform = (units / 24, 0, 0, -units / 24, 0, units)
        parse_path(definition.get('filledPath', definition['path']) if fill else definition['path'],
                   TransformPen(Cu2QuPen(pen, max_err=0.5, reverse_direction=True), transform))
        glyph = pen.glyph()
        order = [*instance.getGlyphOrder(), name]
        instance['glyf'][name] = glyph
        instance.setGlyphOrder(order)
        glyph.recalcBounds(instance['glyf'])
        instance['hmtx'][name] = (units, glyph.xMin)
        for table in instance['cmap'].tables:
            if table.isUnicode():
                table.cmap[codepoints[name]] = name
    instance['OS/2'].usWeightClass = 350
    for name_id, value in [(1,family),(2,'Regular'),(4,family),(6,family)]:
        instance['name'].setName(value,name_id,3,1,0x409)
    path = assets / (family + '.ttf')
    instance.save(path)
    receipt['files'][path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
(ROOT / 'android/design-system/icons/material-symbols-receipt.json').write_text(json.dumps(receipt, indent=2)+'\n')
license_bytes = fetch('LICENSE')
(ROOT / 'android/design-system/icons/MaterialSymbols-LICENSE.txt').write_bytes(license_bytes)
(ROOT / 'android/app/src/main/assets/licenses/MATERIAL-SYMBOLS-LICENSE').write_bytes(license_bytes)
# Both renderers use the same pinned semantic mapping and the same packaged font.
entries = [(alias,codepoints[name]) for alias,name in sorted(config['symbols'].items())]
ts = '// Generated by scripts/generate-material-symbols.py; actual static weight 350.\n'
ts += 'export const materialSymbols:Readonly<Record<string,string>>={\n'
ts += ''.join(f'  {json.dumps(alias)}:"\\u{value:04x}",\n' for alias,value in entries)+'};\n'
ts += "export function materialSymbol(name:string){return materialSymbols[name]??materialSymbols['info.circle'];}\n"
ts += "export function materialSymbolFont(name:string){return name.endsWith('.fill')?'MaterialSymbolsRounded350Filled':'MaterialSymbolsRounded350';}\n"
(ROOT / 'android/react-native/canonical/android/material-symbols.ts').write_text(ts)
kt = '// Generated by scripts/generate-material-symbols.py; actual static weight 350.\npackage com.lavasec.app.reactnative\n\ninternal object MaterialSymbolGlyphs {\n    private val glyphs = mapOf(\n'
kt += ''.join(f'        {json.dumps(alias)} to "\\u{value:04x}",\n' for alias,value in entries)
kt += '    )\n    fun glyph(symbol: String): String = glyphs[symbol] ?: glyphs.getValue("info.circle")\n    fun font(symbol: String): String = if (symbol.endsWith(".fill")) "MaterialSymbolsRounded350Filled" else "MaterialSymbolsRounded350"\n}\n'
(ROOT / 'android/app/src/main/kotlin/com/lavasec/app/reactnative/MaterialSymbolGlyphs.kt').write_text(kt)
print('Generated',len(entries),'aliases;',len(names),'glyphs; two fixed-weight 350 fonts.')
